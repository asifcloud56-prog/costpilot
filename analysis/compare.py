#!/usr/bin/env python3
"""Build the before/after comparison table.

Inputs (created by `make load-before` and `make load-after`):
    results/before_deploy.json, results/after_deploy.json   (Deployment manifests)
    results/before_k6.json,     results/after_k6.json       (k6 --summary-export)

Outputs:
    a table on screen and results/comparison.md
"""
import json
import sys
from pathlib import Path

RESULTS = Path("results")


def load(name: str) -> dict:
    path = RESULTS / name
    if not path.exists():
        print(f"Missing {path}. Follow the workflow in the Makefile (load-before ... load-after).")
        sys.exit(1)
    return json.loads(path.read_text())


def cpu_to_cores(v: str) -> float:
    return float(v[:-1]) / 1000 if v.endswith("m") else float(v)


def mem_to_mib(v: str) -> float:
    units = {"Ki": 1 / 1024, "Mi": 1, "Gi": 1024, "Ti": 1024 * 1024}
    for suffix, mult in units.items():
        if v.endswith(suffix):
            return float(v[: -len(suffix)]) * mult
    return float(v) / (1024 * 1024)  # plain bytes


def requests_of(deploy: dict) -> tuple[float, float, int]:
    spec = deploy["spec"]
    replicas = int(spec.get("replicas", 1))
    res = spec["template"]["spec"]["containers"][0]["resources"]["requests"]
    return cpu_to_cores(res["cpu"]), mem_to_mib(res["memory"]), replicas


def metric(summary: dict, name: str, *keys: str):
    """Read a value from a k6 summary, supporting both the legacy and the newer layouts."""
    m = summary.get("metrics", {}).get(name)
    if m is None:
        return None
    for source in (m, m.get("values", {})):
        for key in keys:
            if key in source:
                return source[key]
    return None


def pct_change(before: float, after: float) -> str:
    if before == 0:
        return "n/a"
    return f"{(after - before) / before * 100:+.0f}%"


def main() -> int:
    b_dep, a_dep = load("before_deploy.json"), load("after_deploy.json")
    b_k6, a_k6 = load("before_k6.json"), load("after_k6.json")

    b_cpu, b_mem, replicas = requests_of(b_dep)
    a_cpu, a_mem, _ = requests_of(a_dep)

    rows = [
        ("CPU requests per pod (cores)", f"{b_cpu:.2f}", f"{a_cpu:.2f}", pct_change(b_cpu, a_cpu)),
        ("Memory requests per pod (MiB)", f"{b_mem:.0f}", f"{a_mem:.0f}", pct_change(b_mem, a_mem)),
        (f"Total CPU requests ({replicas} pods)", f"{b_cpu * replicas:.2f}", f"{a_cpu * replicas:.2f}", pct_change(b_cpu, a_cpu)),
        (f"Total memory requests ({replicas} pods, MiB)", f"{b_mem * replicas:.0f}", f"{a_mem * replicas:.0f}", pct_change(b_mem, a_mem)),
    ]

    for label, names in [
        ("Latency avg (ms)", ("avg",)),
        ("Latency p95 (ms)", ("p(95)",)),
    ]:
        b = metric(b_k6, "http_req_duration", *names)
        a = metric(a_k6, "http_req_duration", *names)
        if b is not None and a is not None:
            rows.append((label, f"{b:.1f}", f"{a:.1f}", pct_change(b, a)))

    b_fail = metric(b_k6, "http_req_failed", "value", "rate")
    a_fail = metric(a_k6, "http_req_failed", "value", "rate")
    if b_fail is not None and a_fail is not None:
        rows.append(("Failed requests (%)", f"{b_fail * 100:.2f}", f"{a_fail * 100:.2f}", ""))

    b_n = metric(b_k6, "http_reqs", "count")
    a_n = metric(a_k6, "http_reqs", "count")
    if b_n is not None and a_n is not None:
        rows.append(("Requests served", f"{b_n:.0f}", f"{a_n:.0f}", ""))

    header = ("Metric", "Before", "After", "Change")
    widths = [max(len(str(r[i])) for r in [header] + rows) for i in range(4)]

    def fmt(r):
        return "| " + " | ".join(str(c).ljust(widths[i]) for i, c in enumerate(r)) + " |"

    lines = [fmt(header), "|" + "|".join("-" * (w + 2) for w in widths) + "|"] + [fmt(r) for r in rows]
    table = "\n".join(lines)
    print(table)

    md = "# Before/after comparison\n\n" + table + "\n\n" \
         "_Same k6 load test and same demo workload in both runs. " \
         "Generated by `analysis/compare.py`._\n"
    (RESULTS / "comparison.md").write_text(md)
    print("\nSaved: results/comparison.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
